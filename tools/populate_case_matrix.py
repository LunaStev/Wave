"""Refresh target workloads from maintained Wave cases without overwriting hand-written tests."""

import argparse
from pathlib import Path
import re

try:
    from tools.case_manifest import CASES_ROOT, DEFAULT_MANIFEST, load_case_manifest
except ModuleNotFoundError:
    from case_manifest import CASES_ROOT, DEFAULT_MANIFEST, load_case_manifest


ARCHITECTURE = {
    "rhea": "arm64", "shakti": "riscv64", "xiangshan": "riscv64", "t-head": "riscv64",
}

ASSEMBLY = {
    "amd64": ('"imul rax, rax, 33"\n        "xor rax, rcx"', 'in("rax") state\n        in("rcx") word\n        out("rax") result'),
    "arm64": ('"add x0, x0, x0, lsl #5"\n        "eor x0, x0, x1"', 'in("x0") state\n        in("x1") word\n        out("x0") result'),
    "riscv64": ('"slli t0, a0, 5"\n        "add a0, a0, t0"\n        "xor a0, a0, a1"', 'in("a0") state\n        in("a1") word\n        out("a0") result\n        clobber("t0")'),
    "loong64": ('"slli.d $t0, $a0, 5"\n        "add.d $a0, $a0, $t0"\n        "xor $a0, $a0, $a1"', 'in("a0") state\n        in("a1") word\n        out("a0") result\n        clobber("t0")'),
}


def target_mix(arch: str) -> str:
    assembly = ASSEMBLY.get(ARCHITECTURE.get(arch, arch))
    if assembly is None:
        return """export(c) fun target_mix(state: u64, word: u64) -> u64 {
    return ((state * 33) ^ word) % 65521;
}
"""
    instructions, operands = assembly
    return f"""fun target_mix(state: u64, word: u64) -> u64 {{
    var result: u64 = asm {{
        {instructions}
        {operands}
    }};
    return result % 65521;
}}
"""


CHECKPOINT = """
// Feed actual records through the target's register calling convention, then
// compare each checkpoint to Wave arithmetic. Live copies and guard words must
// survive every call; the low and high halves of inputs both carry data.
struct TargetBlock { words: array<u64, 16>; digest: u64; guard: u64; }
fun target_block(seed: u64) -> TargetBlock {
    var block: TargetBlock;
    var i: i64 = 0;
    while (i < 16) {
        block.words[i] = 4294967296 + seed * 97 + (i as u64) * 65537;
        i += 1;
    }
    block.digest = seed;
    block.guard = 0xFEDCBA9876543210;
    return block;
}
fun target_workload() -> i32 {
    var round: u64 = 0;
    while (round < 65) {
        var block: TargetBlock = target_block(round);
        var snapshot: TargetBlock = block;
        var reference: u64 = round;
        var i: i64 = 0;
        while (i < 16) {
            var word: u64 = block.words[i];
            block.digest = target_mix(block.digest, word);
            reference = ((reference * 33) ^ word) % 65521;
            if (block.digest != reference) { return 201; }
            if (snapshot.words[i] != word || snapshot.digest != round) { return 202; }
            i += 1;
        }
        if (block.guard != 0xFEDCBA9876543210 || snapshot.guard != block.guard) { return 203; }
        round += 1;
    }
    return 0;
}
"""


def generated_case(relative_suite: str, arch: str, number: int, metadata: str, cases_root=CASES_ROOT) -> str:
    source = cases_root / "shared" / f"test{103 + number}.wave"
    body = source.read_text(encoding="utf-8")
    body = "".join(line for line in body.splitlines(keepends=True)
                   if not line.startswith("// wave-test:"))
    if body.count("fun main() -> i32") != 1:
        raise ValueError(f"expected one workload entry point in {source}")
    body = body.replace("fun main() -> i32", "fun exercise_language() -> i32", 1)
    smoke = '    println("loongarch workload=pass");\n' if relative_suite == "linux/loong64" and number == 2 else ""
    return (metadata + "// Generated by tools/populate_case_matrix.py.\n"
            + f"// {relative_suite}: functional workload {number} and target data transport.\n"
            + body + "\n" + target_mix(arch) + CHECKPOINT + """
fun main() -> i32 {
    var status: i32 = exercise_language();
    if (status != 0) { return status; }
    status = target_workload();
    if (status != 0) { return status; }
""" + smoke + "    return 0;\n}\n")


def refresh_cases(cases_root=CASES_ROOT, manifest_path=DEFAULT_MANIFEST):
    cases_root = Path(cases_root)
    # Reuse the complete manifest contract before writing anything. Generation
    # may create missing suites, so only filesystem layout checks are deferred.
    manifest = load_case_manifest(manifest_path, validate_layout=False)
    suites = {suite for target in manifest.targets for suite in target.suites if suite != "shared"}
    changed = 0
    for suite in sorted(suites):
        directory = cases_root / suite
        existing = list(directory.glob("test*.wave"))
        existing.extend(directory.glob("test*/main.wave"))
        numbers = []
        for path in existing:
            unit = path.parent.name if path.name == "main.wave" else path.stem
            if not re.fullmatch(r"test[1-9][0-9]*", unit):
                raise ValueError(f"invalid case number: {path}")
            numbers.append(int(unit[4:]))
        if sorted(numbers) != list(range(1, len(numbers) + 1)):
            raise ValueError(f"non-contiguous case numbering in {suite}")
        directory.mkdir(parents=True, exist_ok=True)
        for number in range(1, 11):
            path = directory / f"test{number}.wave"
            if (directory / f"test{number}/main.wave").exists():
                continue
            content = path.read_text(encoding="utf-8") if path.exists() else None
            if content is not None and "// Generated by tools/populate_case_matrix.py." not in content:
                continue
            metadata = "".join(line + "\n" for line in (content or "").splitlines()
                               if line.startswith("// wave-test:"))
            replacement = generated_case(suite, directory.name, number, metadata, cases_root)
            if content != replacement:
                path.write_text(replacement, encoding="utf-8")
                changed += 1
    return changed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cases-root", type=Path, default=CASES_ROOT)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    args = parser.parse_args()
    print(f"updated {refresh_cases(args.cases_root, args.manifest)} target workloads")


if __name__ == "__main__":
    main()
